/// Spacing scale — the single source of truth for padding, gaps and margins.
///
/// Use these instead of inline numbers so the whole app breathes on one
/// rhythm. Steps are an 8pt-ish scale with two sub-steps for tight UI.
class AppSpacing {
  AppSpacing._();

  static const double xxs = 2;
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 20;
  static const double xxl = 24;
  static const double xxxl = 32;
  static const double huge = 48;
}
